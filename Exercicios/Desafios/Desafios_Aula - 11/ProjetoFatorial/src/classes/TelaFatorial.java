    private void spiNumStateChanged(javax.swing.event.ChangeEvent evt) {//GEN-FIRST:event_spiNumStateChanged
        // TODO add your handling code here:
        int n = Integer.parseInt(spiNum.getValue().toString()); //SPINNER
        int f = 1;
        int c = n;
        String detalhe = "";
        String bonus = "";
        
        while (c >= 1){
            f *= c;
            if(c != 1){
                detalhe = " X ";
                bonus = bonus + c + detalhe;
            } else {
                bonus = bonus + c + " = " + f;
            }
            c--; 
        }
        //lblResposta.setText(Integer.toString(f));
        lblResposta.setText(bonus);
        
    
        
        
      
        
        
    }//GEN-LAST:event_spiNumStateChanged

